"""Write docs/airtable-schema.md from the real Airtable base.

Run it from the backend folder with: python -m jobs.dump_schema

It lists every table and field with its type, the options of each select field and
the table each link field points to. It reads the schema only, never records.
"""

from app.airtable.client import get_base, is_configured
from app.config import REPO_ROOT

OUTPUT = REPO_ROOT / "docs" / "airtable-schema.md"

NOTES = """
## Notes on the real base

These were found by reading the dump above and decide how the app uses the base.
See docs/decisions.md for the full list of decisions.

- **Work: the person.** `Assigned To` links to Users and is the person. `Assignee`
  is a lookup through Steps (the step's default roles), not a person.
- **Work: dates.** `Due Date` is a formula: `Due Date Override` if set, otherwise
  `Calculated Due Date`, which follows the Session's Start Date. The app always
  writes `Due Date Override`, so dates never move by themselves when Day 1 changes.
- **Work: Task Name, Anchor, Days Before Anchor** are real fields, not lookups.
  `Anchor` is single line text on Work and a single select on Steps.
- **Work: Status** options are Not Started, In Progress, Blocked, Done and Skipped,
  as expected. **Work: Depends On** (link to Work) already exists, so the migration
  does not add it.
- **Session: Status** options are Not started, In progress and Complete.
- **Session: End Date** is a formula from `Start Date` and `Duration (Days)`, so the
  app stores the duration and leaves End Date alone.
- **Session: Session Name** is a formula (date, region and site), so the name an
  admin types is stored in a new `Program Name` field.
- **Session: Drive Folder** and **Site: Drive Folder** already exist.
- **Site: Program Name** is the site's own name (for example "Loop YMCA").
- **Roles: Status** options are Active, On Hold and "In Active" (with a space).
- **Steps: Retired** is an existing checkbox. A ticked step counts as retired.
- **Links: Created** and **Reminders** created times come from Airtable's own record
  creation time, because the metadata API cannot create "created time" fields.
- The tables "Templates - >", "Programs - >" and "WIP - >" are empty dividers and
  are not used.
"""


def describe_field(field, table_names: dict[str, str]) -> str:
    data = field.model_dump()
    options = data.get("options") or {}
    parts = []
    if options.get("choices"):
        parts.append("options: " + ", ".join(c["name"] for c in options["choices"]))
    if options.get("linked_table_id"):
        parts.append("links to " + table_names.get(options["linked_table_id"], "?"))
    if options.get("formula"):
        parts.append("formula")
    if options.get("record_link_field_id"):
        parts.append("lookup")
    result = options.get("result")
    if result and result.get("type"):
        parts.append(f"result {result['type']}")
    return "; ".join(parts)


def main() -> int:
    if not is_configured():
        print("Airtable is not configured. Set AIRTABLE_TOKEN and AIRTABLE_BASE_ID.")
        return 1
    schema = get_base().schema(force=True)
    table_names = {t.id: t.name for t in schema.tables}
    lines = [
        "# Airtable schema",
        "",
        "Generated by `python -m jobs.dump_schema`. Do not edit by hand; run it again.",
        "",
    ]
    for table in schema.tables:
        primary = next(
            (f.name for f in table.fields if f.id == table.primary_field_id), ""
        )
        lines += [
            f"## {table.name}",
            "",
            f"Primary field: {primary}",
            "",
            "| Field | Type | Details |",
            "|---|---|---|",
        ]
        for field in table.fields:
            type_name = getattr(field.type, "value", str(field.type))
            details = describe_field(field, table_names).replace("|", "/")
            lines.append(f"| {field.name} | {type_name} | {details} |")
        lines.append("")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines) + NOTES, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(REPO_ROOT)} with {len(schema.tables)} tables.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
